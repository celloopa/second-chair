// Builds Chord Coach: computes its data from the same TypeScript the second-chair MCP server uses, writes it into
// chordcoach.js (between the GENERATED markers), rebuilds Chord Coach.amxd, and with --install copies both into
// Live's User Library. Max's jsui runs old-style JavaScript, so it gets plain data, not the TypeScript itself.
//
//   node chord-coach\build.ts            build only
//   node chord-coach\build.ts --install  build and copy into the User Library (then reload the device in Live)

import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { execFileSync } from "node:child_process";
import { parseChordSymbol, keysFor, chordShape, RING_MS, TRAIL_HOLD_MS, BLOCK_MS } from "../live-bridge/mcp/chords.ts";

const HERE = import.meta.dirname;
const JS = path.join(HERE, "chordcoach.js");
const AMXD = path.join(HERE, "Chord Coach.amxd");
// Where Live's User Library keeps the device: nested on the Windows PC, not on the Mac.
const INSTALL = process.platform === "darwin"
  ? path.join(os.homedir(), "Music", "Ableton", "User Library", "Presets", "MIDI Effects", "Max MIDI Effect", "Chord Coach")
  : "C:\\Users\\rondo\\Music\\Ableton\\User Library\\User Library\\Presets\\MIDI Effects\\Max MIDI Effect\\Chord Coach";

// The E Dorian interlude. Voicings come from Spur's voicing.ts via keysFor(); the guitar and bass hints stay in chordcoach.js.
const PROGRESSION = ["Em9", "A13", "Cmaj9", "B7b9"];

const ascii = (s: string) => s.replace(/♭/g, "b").replace(/♯/g, "#");
const pc = (n: number) => ((n % 12) + 12) % 12;

const prog = PROGRESSION.map((sym) => {
  const c = parseChordSymbol(sym);
  const keys = keysFor(c.pcs, c.bass);
  return { nm: sym, root: c.root, pcs: [...new Set(keys.map(pc))], keys };
});

// Every set of notes above a bass (bit 0 = the bass), 2 to 6 notes, named with the same logic as theory_name_chord.
// Entry: [root above the bass in semitones, suffix, extension mask (bits above the bass)].
const table: Record<number, [number, string, number]> = {};
for (let mask = 1; mask < 4096; mask += 2) {
  const bits = [...Array(12).keys()].filter((i) => mask & (1 << i));
  if (bits.length < 2 || bits.length > 6) continue;
  const s = chordShape(bits.map((i) => 48 + i));
  if (!s) continue;
  if (s.ext) { table[mask] = [0, ascii(s.ext.suffix), 0]; continue; }
  const ext = s.extensions.reduce((m, n) => m | (1 << pc(n)), 0);
  table[mask] = [pc(s.heard.root), ascii(s.heard.suffix), ext];
}

const generated = [
  "// BEGIN GENERATED by build.ts from live-bridge/mcp/chords.ts and Spur's voicing.ts. Don't edit by hand.",
  `var GEN_PROG = ${JSON.stringify(prog)};`,
  `var GEN_CHORDS = ${JSON.stringify(table)};`,
  `var RING_MS = ${RING_MS}, TRAIL_HOLD_MS = ${TRAIL_HOLD_MS}, BLOCK_MS = ${BLOCK_MS};`,
  "// END GENERATED",
].join("\n");

const src = fs.readFileSync(JS, "utf8");
const re = /\/\/ BEGIN GENERATED[\s\S]*?\/\/ END GENERATED/;
if (!re.test(src)) throw new Error("chordcoach.js has no GENERATED markers");
fs.writeFileSync(JS, src.replace(re, () => generated));
console.log(`chordcoach.js: ${prog.map((p) => `${p.nm} ${JSON.stringify(p.keys)}`).join(", ")}; ${Object.keys(table).length} chord shapes`);

// A stock Mac has only python3; Windows has python (its python3 can be a Microsoft Store stub). Try the likely one first.
const PYTHONS = process.platform === "win32" ? ["python", "python3"] : ["python3", "python"];
for (const [i, py] of PYTHONS.entries()) {
  try { execFileSync(py, [path.join(HERE, "make_amxd.py"), AMXD], { stdio: "inherit" }); break; }
  catch (e: any) { if (e.code !== "ENOENT" || i === PYTHONS.length - 1) throw e; }
}

if (process.argv.includes("--install")) {
  fs.mkdirSync(INSTALL, { recursive: true });
  for (const f of [JS, AMXD]) fs.copyFileSync(f, path.join(INSTALL, path.basename(f)));
  console.log("installed to", INSTALL);
}
